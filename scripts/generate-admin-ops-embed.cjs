#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const opsDir = path.join(root, 'data', 'ops');
const outFile = path.join(root, 'js', 'admin', 'ops-json-embed.js');

if (!fs.existsSync(opsDir)) {
  console.error('Missing data/ops directory');
  process.exit(1);
}

const embed = {};
for (const name of fs.readdirSync(opsDir)) {
  if (!name.endsWith('.json')) continue;
  const key = name.replace(/\.json$/, '');
  embed[key] = JSON.parse(fs.readFileSync(path.join(opsDir, name), 'utf8'));
}

const banner = '/** Auto-generated by scripts/generate-admin-ops-embed.cjs — do not edit */\n';
fs.writeFileSync(outFile, `${banner}export const OPS_JSON_EMBED = ${JSON.stringify(embed)};\n`);
console.log(`Wrote ${outFile} (${Object.keys(embed).length} configs)`);
