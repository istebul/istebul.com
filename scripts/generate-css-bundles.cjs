#!/usr/bin/env node
/**
 * Regenerate css/bundles/*.bundle.css from scripts/lib/css-bundles.cjs manifests.
 */
const fs = require('fs');
const path = require('path');
const { BUNDLES } = require('./lib/css-bundles.cjs');

const root = process.cwd();

for (const [bundlePath, sources] of Object.entries(BUNDLES)) {
  const abs = path.join(root, bundlePath);
  fs.mkdirSync(path.dirname(abs), { recursive: true });

  const lines = [
    `/* Generated by scripts/generate-css-bundles.cjs — do not edit by hand */`,
    `/* Manifest: scripts/lib/css-bundles.cjs */`,
    ''
  ];

  for (const rel of sources) {
    const full = path.join(root, rel);
    if (!fs.existsSync(full)) {
      console.error(`MISSING source for bundle ${bundlePath}: ${rel}`);
      process.exit(1);
    }
    const importPath = path.relative(path.dirname(abs), full).split(path.sep).join('/');
    lines.push(`@import '${importPath}';`);
  }

  lines.push('');
  fs.writeFileSync(abs, lines.join('\n'));
}

console.log(`generate-css-bundles: ${Object.keys(BUNDLES).length} bundle(s) OK`);
