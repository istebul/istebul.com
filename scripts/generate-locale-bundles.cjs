#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');

const root = path.join(__dirname, '..');
const outDir = path.join(root, 'js/features/i18n/locale-bundles');

async function main() {
  const marketingPath = path.join(root, 'js/features/i18n/marketing-copy.js');
  const { marketingCopy } = await import(pathToFileURL(marketingPath).href);

  fs.mkdirSync(outDir, { recursive: true });

  for (const [localeId, copy] of Object.entries(marketingCopy)) {
    const target = path.join(outDir, `${localeId}.js`);
    const body = `/** Generated by scripts/generate-locale-bundles.cjs — do not edit */\nexport default ${JSON.stringify(copy)};\n`;
    fs.writeFileSync(target, body);
  }

  console.log(`Generated ${Object.keys(marketingCopy).length} locale bundles in js/features/i18n/locale-bundles/`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
