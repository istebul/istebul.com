const fs = require('fs');
const path = require('path');

const metaPath = path.join(__dirname, '../../data/route-document-meta.json');
const outputPath = path.join(__dirname, '../../js/runtime/route-bootstrap-head.js');

function loadRouteMeta() {
  return JSON.parse(fs.readFileSync(metaPath, 'utf8'));
}

/**
 * Head bootstrap: route surface + document meta (keep in sync with js/runtime/route-surface.js).
 */
function buildRouteBootstrapScript() {
  const { siteOrigin, surfaces } = loadRouteMeta();
  const metaJson = JSON.stringify(surfaces);
  const originJson = JSON.stringify(siteOrigin);

  return `(function(){var O=${originJson},M=${metaJson},p=(location.pathname||'/').replace(/\\/$/,'')||'/',m=p.match(/^\\/(en|de)(\\/|$)/);if(m)p=p.slice(m[1].length+1)||'/';p=p.replace(/\\/$/,'')||'/';if(p==='/partner'){location.replace('/partner-olun.html');return}var prem={'/karar-analizi':'page-karar-analizi','/metodoloji':'page-metodoloji','/planlar':'page-planlar','/karar-asistani':'page-karar-analizi','/duyurular':'page-duyurular','/kampanyalar':'page-kampanyalar','/blog':'page-blog'};var app={'/ilanlar':'ilanlar','/karsilastir':'compare','/favoriler':'favoriler','/gecmis':'history','/quiz':'quiz','/profil':'profil','/hesap':'profil','/messages':'messages','/ilan-ekle':'add-listing'};var r=prem[p]||app[p]||(p.indexOf('/blog/')===0?'page-blog-post':p.indexOf('/ilan/')===0?'listing-detail':'home');var d=document.documentElement;d.setAttribute('data-ib-route',r);d.classList.remove('ib-route-pending');var meta=M[r]||M.home;var path=meta.path||'/';var url=O+(path==='/'?'/':path);document.title=meta.title;var desc=document.getElementById('meta-description');if(desc)desc.setAttribute('content',meta.description);var can=document.getElementById('meta-canonical');if(can)can.setAttribute('href',url);var ogt=document.getElementById('meta-og-title');if(ogt)ogt.setAttribute('content',meta.title);var ogd=document.getElementById('meta-og-description');if(ogd)ogd.setAttribute('content',meta.description);var ogu=document.getElementById('meta-og-url');if(ogu)ogu.setAttribute('content',url);var twt=document.getElementById('meta-twitter-title');if(twt)twt.setAttribute('content',meta.title);var twd=document.getElementById('meta-twitter-description');if(twd)twd.setAttribute('content',meta.description);})();`;
}

function writeRouteBootstrapFile(targetPath = outputPath) {
  const script = buildRouteBootstrapScript();
  fs.mkdirSync(path.dirname(targetPath), { recursive: true });
  fs.writeFileSync(
    targetPath,
    `/* Generated by scripts/lib/route-bootstrap.cjs — do not edit by hand */\n${script}\n`,
    'utf8'
  );
  return targetPath;
}

const BOOTSTRAP_MARKERS = /<!-- ROUTE_BOOTSTRAP_START -->[\s\S]*?<!-- ROUTE_BOOTSTRAP_END -->/;

function injectRouteBootstrap(html) {
  if (!BOOTSTRAP_MARKERS.test(html)) {
    throw new Error('index.html missing ROUTE_BOOTSTRAP markers');
  }

  const block = `<!-- ROUTE_BOOTSTRAP_START -->
    <script src="/js/runtime/route-bootstrap-head.js"></script>
    <!-- ROUTE_BOOTSTRAP_END -->`;

  return html.replace(BOOTSTRAP_MARKERS, block);
}

function assertNoInlineRouteBootstrap(html) {
  const inline = /<script>\s*\/\* ROUTE_BOOTSTRAP_START/i.test(html);
  if (inline) {
    throw new Error('index.html must not contain inline route bootstrap script');
  }
}

module.exports = {
  loadRouteMeta,
  buildRouteBootstrapScript,
  writeRouteBootstrapFile,
  injectRouteBootstrap,
  assertNoInlineRouteBootstrap
};
